import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { tenantLocalizationAudit } from "./audit-tenant-localization.mjs";

const root = resolve(import.meta.dirname, "..");
const catalogDirectory = resolve(root, "localization");
const sourcePath = resolve(catalogDirectory, "tenant-ui.source.json");
const arabicPath = resolve(catalogDirectory, "tenant-ui.ar.json");
const webKeyMapPath = resolve(
  root,
  "apps/web/src/i18n/generated-tenant-ui-keys.ts",
);
const arabicOverridesPath = resolve(
  catalogDirectory,
  "tenant-ui.ar.overrides.json",
);
const shouldTranslateArabic = process.argv.includes("--translate-ar");
const translationProvider =
  process.env.TRANSLATION_PROVIDER ?? "libretranslate";

const grouped = new Map();
for (const finding of tenantLocalizationAudit.catalogFindings) {
  const existing = grouped.get(finding.text);
  if (existing) {
    existing.sources.push(`${finding.file}:${finding.line}`);
    continue;
  }
  grouped.set(finding.text, {
    key: catalogKey(finding.text),
    namespace: namespaceFor(finding.file),
    defaultMessage: finding.text,
    description: `Tenant UI copy used at ${finding.file}:${finding.line}`,
    sources: [`${finding.file}:${finding.line}`],
  });
}

const entries = [...grouped.values()].sort((left, right) =>
  left.key.localeCompare(right.key),
);
mkdirSync(catalogDirectory, { recursive: true });
writeJson(sourcePath, {
  audit: tenantLocalizationAudit.summary,
  entries,
});
writeFileSync(
  webKeyMapPath,
  [
    "// Generated by scripts/generate-localization-catalog.mjs. Do not edit manually.",
    "export const tenantUiKeyByDefaultMessage: Readonly<Record<string, string>> =",
    `${JSON.stringify(
      Object.fromEntries(
        entries.map(({ defaultMessage, key }) => [defaultMessage, key]),
      ),
      null,
      2,
    )};`,
    "",
  ].join("\n"),
);

const arabicOverrides = readArabicOverrides(arabicOverridesPath);
let translations = readTranslations(arabicPath);
for (const entry of entries) {
  const override = arabicOverrides.translations[entry.defaultMessage];
  if (override) translations.set(entry.key, override);
}
if (shouldTranslateArabic) {
  translations = await translateMissing(entries, translations);
}
writeJson(arabicPath, {
  locale: "ar",
  reviewRequired: true,
  translations: entries.map(({ key }) => ({
    key,
    value: translations.get(key) ?? "",
  })),
});

const translated = entries.filter(({ key }) => translations.get(key)).length;
console.log(
  `Generated ${entries.length} tenant UI keys. Arabic drafts: ${translated}/${entries.length}.`,
);
console.log(`Source: ${sourcePath}`);
console.log(`Arabic: ${arabicPath}`);
if (!shouldTranslateArabic && translated < entries.length) {
  console.log(
    "Run with --translate-ar to fill missing Arabic drafts using the configured local translation endpoint.",
  );
}

function catalogKey(message) {
  const slug = message
    .toLowerCase()
    .replace(/\{[^}]+\}/g, "")
    .replace(/[^a-z0-9]+/g, ".")
    .replace(/^\.+|\.+$/g, "")
    .split(".")
    .filter(Boolean)
    .slice(0, 8)
    .join(".");
  const digest = createHash("sha1").update(message).digest("hex").slice(0, 8);
  return `tenant.ui.${slug || "message"}.${digest}`;
}

function namespaceFor(file) {
  if (file.includes("/attendance/")) return "attendance-ui";
  if (file.includes("/organization/")) return "organization-ui";
  if (file.includes("/workspace-settings/")) return "settings-ui";
  if (file.startsWith("shared/")) return "shared-ui";
  return "tenant-ui";
}

function readTranslations(path) {
  try {
    const parsed = JSON.parse(readFileSync(path, "utf8"));
    return new Map(
      (parsed.translations ?? []).map(({ key, value }) => [key, value]),
    );
  } catch {
    return new Map();
  }
}

function readArabicOverrides(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return { translations: {}, intentionallyUntranslated: [] };
  }
}

async function translateMissing(sourceEntries, existing) {
  const missing = sourceEntries.filter(({ key }) => !existing.get(key));
  const endpointValue = process.env.TRANSLATION_API_URL;
  if (!endpointValue) {
    throw new Error(
      "Set TRANSLATION_API_URL to an approved private or local translation endpoint.",
    );
  }
  const endpoint = new URL(endpointValue);
  if (
    !["localhost", "127.0.0.1", "::1"].includes(endpoint.hostname) &&
    process.env.ALLOW_EXTERNAL_TRANSLATION !== "true"
  ) {
    throw new Error(
      "External translation sends UI copy outside the repository. Set ALLOW_EXTERNAL_TRANSLATION=true only after approving that transfer.",
    );
  }
  const concurrency = Number(process.env.TRANSLATION_CONCURRENCY ?? 4);
  let cursor = 0;

  async function worker() {
    while (cursor < missing.length) {
      const entry = missing[cursor++];
      const value = await translate(entry.defaultMessage, endpoint);
      existing.set(entry.key, value);
      if (cursor % 25 === 0 || cursor === missing.length) {
        writeJson(arabicPath, {
          locale: "ar",
          reviewRequired: true,
          translations: sourceEntries.map(({ key }) => ({
            key,
            value: existing.get(key) ?? "",
          })),
        });
        console.log(`Translated ${cursor}/${missing.length} missing messages.`);
      }
    }
  }

  await Promise.all(
    Array.from(
      { length: Math.max(1, Math.min(concurrency, missing.length)) },
      worker,
    ),
  );
  return existing;
}

async function translate(message, endpoint) {
  const { protectedText, placeholders } = protectPlaceholders(message);
  if (translationProvider === "libretranslate") {
    return translateWithLibreTranslate(
      protectedText,
      placeholders,
      message,
      endpoint,
    );
  }
  return translateWithGoogleCompatible(
    protectedText,
    placeholders,
    message,
    endpoint,
  );
}

async function translateWithLibreTranslate(
  protectedText,
  placeholders,
  originalMessage,
  endpoint,
) {
  for (let attempt = 1; attempt <= 4; attempt += 1) {
    const response = await fetch(endpoint, {
      method: "POST",
      headers: {
        Accept: "application/json",
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        q: protectedText,
        source: "en",
        target: "ar",
        format: "text",
      }),
    });
    if (response.ok) {
      const payload = await response.json();
      if (payload?.translatedText) {
        return restorePlaceholders(payload.translatedText, placeholders);
      }
    }
    if (attempt === 4) {
      throw new Error(
        `Arabic translation failed (${response.status}) for: ${originalMessage}`,
      );
    }
    await delay(attempt * 750);
  }
}

async function translateWithGoogleCompatible(
  protectedText,
  placeholders,
  originalMessage,
  endpoint,
) {
  const url = new URL(endpoint);
  url.searchParams.set("client", "gtx");
  url.searchParams.set("sl", "en");
  url.searchParams.set("tl", "ar");
  url.searchParams.set("dt", "t");
  url.searchParams.set("q", protectedText);

  for (let attempt = 1; attempt <= 4; attempt += 1) {
    const response = await fetch(url, {
      headers: { Accept: "application/json" },
    });
    if (response.ok) {
      const payload = await response.json();
      const translated = payload?.[0]
        ?.map((segment) => segment?.[0] ?? "")
        .join("");
      if (translated) return restorePlaceholders(translated, placeholders);
    }
    if (attempt === 4) {
      throw new Error(
        `Arabic translation failed (${response.status}) for: ${originalMessage}`,
      );
    }
    await delay(attempt * 750);
  }
}

function protectPlaceholders(message) {
  const placeholders = [];
  const protectedText = message.replace(
    /\{[^{}]+\}|https?:\/\/\S+/g,
    (placeholder) => {
      const token = `ZXQPH${placeholders.length}QXZ`;
      placeholders.push({ token, placeholder });
      return token;
    },
  );
  return { protectedText, placeholders };
}

function restorePlaceholders(message, placeholders) {
  return placeholders.reduce(
    (value, { token, placeholder }) =>
      value
        .replaceAll(token, placeholder)
        .replaceAll(token.toLowerCase(), placeholder),
    message,
  );
}

function writeJson(path, value) {
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`, "utf8");
}

function delay(milliseconds) {
  return new Promise((resolveDelay) => setTimeout(resolveDelay, milliseconds));
}
